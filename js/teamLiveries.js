export function getCarNumber(carIdx, isPlayer = false) {
  if (isPlayer) return 7;
  if (typeof carIdx === 'number' && carIdx >= 0 && carIdx < F1_CAR_NUMBERS.length) {
    return F1_CAR_NUMBERS[carIdx];
  }
  return typeof carIdx === 'number' ? (carIdx + 1) : 1;
}

